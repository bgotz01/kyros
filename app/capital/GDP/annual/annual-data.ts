// ─── build dataset ────────────────────────────────────────────────────────────

export const ALL_COUNTRIES = Object.keys(NOMINAL_RAW);

export const ANNUAL_DATA: AnnualYear[] = (() => {
    const years: AnnualYear[] = [];
    for (let y = 1980; y <= 2025; y++) {
        const entries: AnnualEntry[] = [];
        for (const country of ALL_COUNTRIES) {
            const nomRaw = NOMINAL_RAW[country]?.[y];
            if (nomRaw == null) continue;
            const nominalBn = nomRaw / 1000;
            const pppBn = PPP_RAW[country]?.[y] ?? 0;
            const population = getPopulation(country, y) ?? 0;
            entries.push({ country, nominalBn, pppBn, population });
        }
        if (entries.length === 0) continue;
        entries.sort((a, b) => b.nominalBn - a.nominalBn);
        years.push({ year: y, entries });
    }
    return years;
})();

// ─── top-N helpers ────────────────────────────────────────────────────────────

export function topByNominal(year: AnnualYear, n: number): AnnualEntry[] {
    return year.entries.slice(0, n);
}

export function topByPPP(year: AnnualYear, n: number): AnnualEntry[] {
    return [...year.entries]
        .filter((e) => e.pppBn > 0)
        .sort((a, b) => b.pppBn - a.pppBn)
        .slice(0, n);
}

export function topByRatio(year: AnnualYear, n: number): AnnualEntry[] {
    return [...year.entries]
        .filter((e) => e.pppBn > 0 && e.nominalBn > 0)
        .sort((a, b) => (b.pppBn / b.nominalBn) - (a.pppBn / a.nominalBn))
        .slice(0, n);
}

/** True if the selected year has PPP data */
export function hasPPP(year: AnnualYear): boolean {
    return year.entries.some((e) => e.pppBn > 0);
}

// ─── per-capita helpers ───────────────────────────────────────────────────────

/** Nominal GDP per capita in USD (thousands) */
export function nominalPerCapita(e: AnnualEntry): number {
    if (!e.population) return 0;
    return (e.nominalBn * 1e9) / e.population;
}

/** PPP GDP per capita in current international $ */
export function pppPerCapita(e: AnnualEntry): number {
    if (!e.population || !e.pppBn) return 0;
    return (e.pppBn * 1e9) / e.population;
}

/** PPP/Nominal ratio (unchanged by per-capita, but included for symmetry) */
export function ratioValue(e: AnnualEntry): number {
    if (!e.nominalBn) return 0;
    return e.pppBn / e.nominalBn;
}

export function topByNominalPerCapita(year: AnnualYear, n: number): AnnualEntry[] {
    return [...year.entries]
        .filter((e) => e.population > 0)
        .sort((a, b) => nominalPerCapita(b) - nominalPerCapita(a))
        .slice(0, n);
}

export function topByPPPPerCapita(year: AnnualYear, n: number): AnnualEntry[] {
    return [...year.entries]
        .filter((e) => e.population > 0 && e.pppBn > 0)
        .sort((a, b) => pppPerCapita(b) - pppPerCapita(a))
        .slice(0, n);
}

export function topByRatioPerCapita(year: AnnualYear, n: number): AnnualEntry[] {
    // ratio is independent of population — same ranking as topByRatio
    return topByRatio(year, n);
}
