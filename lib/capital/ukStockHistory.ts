/** Map from YYYY-MM (first of month) to index value. */
const INDEX_BY_MONTH = new Map<string, number>(
    RAW.map(([date, v]) => [date.slice(0, 7), v]),
);

/** First year covered by this dataset. */
export const UK_RETURNS_FROM = 1957;

/** Last year fully covered (FTSE live data takes over at 1984). */
export const UK_HISTORICAL_TO = 1983;

/**
 * True when this dataset should be used for the given decade start year —
 * i.e. the decade predates FTSE coverage (1984) and the dataset has data.
 */
export function isUkHistorical(decadeStart: number): boolean {
    return decadeStart < 1984 && decadeStart + 9 >= UK_RETURNS_FROM;
}

/**
 * Compute the decade price return as (last / first − 1) × 100 using monthly
 * index values. Uses the first available reading at or after startYear-01
 * and the last available reading at or before endYear-12.
 *
 * Returns null if the window has no data.
 */
export function ukDecadeReturn(startYear: number, endYear: number): number | null {
    let first: number | null = null;
    let last: number | null = null;

    for (let y = startYear; y <= endYear; y++) {
        for (let m = 1; m <= 12; m++) {
            const key = `${y}-${String(m).padStart(2, '0')}`;
            const v = INDEX_BY_MONTH.get(key);
            if (v == null) continue;
            if (first == null) first = v;
            last = v;
        }
    }

    if (first == null || last == null || first === 0) return null;
    return (last / first - 1) * 100;
}

/**
 * Count of years that have at least one monthly reading in [startYear, endYear].
 * Used for CAGR calculation.
 */
export function ukDecadeYears(startYear: number, endYear: number): number {
    let firstYear: number | null = null;
    let lastYear: number | null = null;

    for (let y = startYear; y <= endYear; y++) {
        for (let m = 1; m <= 12; m++) {
            const key = `${y}-${String(m).padStart(2, '0')}`;
            if (INDEX_BY_MONTH.has(key)) {
                if (firstYear == null) firstYear = y;
                lastYear = y;
                break;
            }
        }
    }

    if (firstYear == null || lastYear == null) return 1;
    return Math.max(lastYear - firstYear, 1);
}
